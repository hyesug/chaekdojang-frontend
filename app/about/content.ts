// "2026-10-30" → "2026년 10월 30일" (소개·가이드 글의 작성일·수정일 표시)
export function formatKoreanDate(value: string) {
  const [year, month, day] = value.split("-");
  return `${year}년 ${Number(month)}월 ${Number(day)}일`;
}

